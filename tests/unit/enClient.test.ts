// The browser's trimmed English (src/lib/i18n/en.client.ts, round 565): every phrase browser code can
// show, and nothing else, so a first visit downloads less. This test finds those phrases the way the
// browser bundle does (every "use client" file and everything it imports, plus keys that server files
// hand to <T k=…> and *Key= props) and fails when en.client.ts lacks one.
// Regenerate after adding phrases:   UPDATE_EN_CLIENT=1 npx vitest run tests/unit/enClient.test.ts
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, normalize } from "node:path";
import { describe, expect, it } from "vitest";
import { en } from "@/lib/i18n/enFull";
import { en as clientEn } from "@/lib/i18n/en.client";
import { es } from "@/lib/i18n/es";
import { ja } from "@/lib/i18n/ja";
import { fr } from "@/lib/i18n/fr";
import { es as clientEs } from "@/lib/i18n/es.client";
import { ja as clientJa } from "@/lib/i18n/ja.client";
import { fr as clientFr } from "@/lib/i18n/fr.client";

// Spanish, Japanese and French get the same trimming (round 746): a visitor reading one of them used to
// download all of it, about twice what an English visitor downloads.
const OTHERS = [
  { lang: "es", full: es as Record<string, string>, client: clientEs as Record<string, string> },
  { lang: "ja", full: ja as Record<string, string>, client: clientJa as Record<string, string> },
  { lang: "fr", full: fr as Record<string, string>, client: clientFr as Record<string, string> },
];

const SRC = "src";
const OUT = "src/lib/i18n/en.client.ts";

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(name)) out.push(normalize(p).replace(/\\/g, "/"));
  }
  return out;
}

/** The keys browser code can show. */
export function browserKeys(): Set<string> {
  const all = new Set(Object.keys(en));
  const files = new Map(walk(SRC).map((p) => [p, readFileSync(p, "utf8")]));
  const resolve = (from: string, spec: string): string | null => {
    let base: string;
    if (spec.startsWith("@/")) base = `${SRC}/${spec.slice(2)}`;
    else if (spec.startsWith(".")) base = normalize(join(dirname(from), spec)).replace(/\\/g, "/");
    else return null;
    for (const c of [`${base}.ts`, `${base}.tsx`, `${base}/index.ts`, `${base}/index.tsx`, base]) if (files.has(c)) return c;
    return null;
  };
  // Every file the browser bundle can include: "use client" files and what they import (not type-only).
  const seen = new Set<string>();
  const stack = [...files].filter(([, s]) => /^\s*["']use client["']/.test(s)).map(([p]) => p);
  while (stack.length) {
    const p = stack.pop()!;
    if (seen.has(p)) continue;
    seen.add(p);
    if (p.includes("/i18n/")) continue;
    for (const m of files.get(p)!.matchAll(/(?:import|export)\s(?!type\s)[^;]*?from\s+["']([^"']+)["']|import\(["']([^"']+)["']\)/g)) {
      const r = resolve(p, m[1] ?? m[2]);
      if (r) stack.push(r);
    }
  }
  const need = new Set<string>();
  const prefixes = new Set<string>();
  for (const p of seen) {
    const s = files.get(p)!;
    for (const m of s.matchAll(/["'`]([a-zA-Z][a-zA-Z0-9_]*\.[a-zA-Z0-9_.]+)["'`]/g)) if (all.has(m[1])) need.add(m[1]);
    for (const m of s.matchAll(/`([a-zA-Z][a-zA-Z0-9_]*\.[a-zA-Z0-9_.]*)\$\{/g)) prefixes.add(m[1]);
  }
  // Server files handing keys to browser components: <T k="…">, labelKey="…", and `k={`prefix.${x}`}`.
  for (const s of files.values()) {
    for (const m of s.matchAll(/\b(?:k|label|[a-zA-Z]*Key)=["']([^"']+)["']/g)) if (all.has(m[1])) need.add(m[1]);
    for (const m of s.matchAll(/\b(?:k|label|[a-zA-Z]*Key)=\{`([^`$]*)\$\{/g)) prefixes.add(m[1]);
  }
  for (const pre of prefixes) if (pre.includes(".")) for (const k of all) if (k.startsWith(pre)) need.add(k);
  return need;
}

describe("the browser's trimmed English", () => {
  const need = browserKeys();

  if (process.env.UPDATE_EN_CLIENT) {
    it("writes en.client.ts", () => {
      const keys = Object.keys(en).filter((k) => need.has(k));
      const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify((en as Record<string, string>)[k])},`).join("\n");
      writeFileSync(
        OUT,
        `// GENERATED by tests/unit/enClient.test.ts: do not edit. The English phrases browser code shows
// (round 565); next.config.ts gives browser builds this file in place of en.ts. Regenerate with
//   UPDATE_EN_CLIENT=1 npx vitest run tests/unit/enClient.test.ts
import type { en as full } from "./en";
export type { MessageKey } from "./en";

export const en = {
${body}
} as unknown as typeof full;
`,
      );
      expect(existsSync(OUT)).toBe(true);
      for (const { lang, full } of OTHERS) {
        const lines = keys.filter((k) => k in full).map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(full[k])},`).join("\n");
        writeFileSync(
          `src/lib/i18n/${lang}.client.ts`,
          `// GENERATED by tests/unit/enClient.test.ts: do not edit. The phrases browser code shows, in this
// language (round 746); next.config.ts gives browser builds this file in place of ${lang}.ts. Regenerate with
//   UPDATE_EN_CLIENT=1 npx vitest run tests/unit/enClient.test.ts
import type { MessageKey } from "./en";

export const ${lang} = {
${lines}
} as unknown as Record<MessageKey, string>;
`,
        );
      }
    });
    return;
  }

  it("has the same phrases, word for word, in Spanish, Japanese and French", () => {
    for (const { lang, full, client } of OTHERS) {
      const missing = [...need].filter((k) => k in full && !(k in client));
      const changed = Object.entries(client).filter(([k, v]) => full[k] !== v).map(([k]) => k);
      expect({ lang, missing, changed }, "run: UPDATE_EN_CLIENT=1 npx vitest run tests/unit/enClient.test.ts").toEqual({ lang, missing: [], changed: [] });
    }
  });

  it("has every phrase browser code can show", () => {
    const missing = [...need].filter((k) => !(k in clientEn));
    expect(missing, "run: UPDATE_EN_CLIENT=1 npx vitest run tests/unit/enClient.test.ts").toEqual([]);
  });

  it("matches the full English word for word", () => {
    const changed = Object.entries(clientEn).filter(([k, v]) => (en as Record<string, string>)[k] !== v).map(([k]) => k);
    expect(changed, "run: UPDATE_EN_CLIENT=1 npx vitest run tests/unit/enClient.test.ts").toEqual([]);
  });

  it("is smaller than the full English", () => {
    expect(Object.keys(clientEn).length).toBeLessThan(Object.keys(en).length * 0.8);
  });
});
