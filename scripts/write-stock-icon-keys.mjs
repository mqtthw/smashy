// Rewrites src/lib/stockIconKeys.ts from the files in public/stock/<game>/<key>.webp.
// Run on its own after adding or removing icons: node scripts/write-stock-icon-keys.mjs
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";

export function writeStockIconKeys() {
  const games = readdirSync("public/stock").filter((g) => statSync(`public/stock/${g}`).isDirectory()).sort();
  const lines = games.map((g) => {
    const keys = readdirSync(`public/stock/${g}`).filter((f) => f.endsWith(".webp")).map((f) => f.slice(0, -5)).sort();
    return `  ${g}: new Set(${JSON.stringify(keys)}),`;
  });
  writeFileSync(
    "src/lib/stockIconKeys.ts",
    `// Generated by scripts/write-stock-icon-keys.mjs: characters with a stock icon in public/stock/<game>/<key>.webp.\nimport type { GameKey } from "./games";\n\nexport const STOCK_ICON_KEYS: Partial<Record<GameKey, ReadonlySet<string>>> = {\n${lines.join("\n")}\n};\n`,
  );
  return games.length;
}

if (process.argv[1]?.includes("write-stock-icon-keys") && existsSync("public/stock")) console.log(`${writeStockIconKeys()} games`);
